#!/usr/bin/env python3
"""
Export legacy Streamlit/LangChain chat JSON files into SQL for this platform.

The legacy system stores one history_chat.json per user and records those paths
in config.json under "history_chat_path". This script uses only Python's
standard library and produces idempotent INSERT statements with deterministic
UUIDs, so the same SQL can be re-run safely.
"""

from __future__ import annotations

import argparse
import json
import sys
import uuid
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any


NAMESPACE = uuid.UUID("8a38afbb-2d5e-4cb5-a344-cc4b6d2343a1")
VALID_ROLES = {"system", "user", "assistant"}


def sql_literal(value: str | None) -> str:
    if value is None:
        return "NULL"
    return "'" + value.replace("'", "''") + "'"


def clamp(value: str, length: int) -> str:
    return value if len(value) <= length else value[:length]


def parse_time(value: Any) -> datetime:
    if isinstance(value, str):
        for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M"):
            try:
                return datetime.strptime(value, fmt)
            except ValueError:
                pass
    return datetime.now()


def normalize_message(message: dict[str, Any]) -> tuple[str, str, str | None]:
    role = str(message.get("role") or "user").strip().lower()
    if role not in VALID_ROLES:
        role = "user"
    content = message.get("content")
    if isinstance(content, list):
        text_parts = []
        for part in content:
            if isinstance(part, dict) and part.get("type") == "text":
                text_parts.append(str(part.get("text") or ""))
            elif isinstance(part, str):
                text_parts.append(part)
        content = "\n".join(part for part in text_parts if part)
    elif content is None:
        content = ""
    else:
        content = str(content)
    reasoning = message.get("reasoning_content")
    reasoning_text = str(reasoning) if reasoning else None
    return role, content, reasoning_text


def load_conversations(history_path: Path) -> dict[str, dict[str, Any]]:
    data = json.loads(history_path.read_text(encoding="utf-8"))
    result: dict[str, dict[str, Any]] = {}
    titles: list[str] = []
    seen: set[str] = set()
    for title in data.get("title") or []:
        if isinstance(title, str) and title and title not in seen:
            seen.add(title)
            titles.append(title)
    for source_key in ("history_messages", "think_message"):
        source = data.get(source_key) or {}
        if isinstance(source, dict):
            for title in source.keys():
                if isinstance(title, str) and title and title not in seen:
                    seen.add(title)
                    titles.append(title)
    for title in titles:
        think_payload = (data.get("think_message") or {}).get(title)
        history_payload = (data.get("history_messages") or {}).get(title)
        payload = think_payload if isinstance(think_payload, dict) and isinstance(think_payload.get("messages"), list) else history_payload
        if isinstance(payload, dict):
            messages = payload.get("messages", [])
            if isinstance(messages, list) and messages:
                result[str(title)] = {
                    "time": payload.get("time"),
                    "messages": messages,
                }
    return result


def resolve_history_path(raw_path: str, data_root: Path | None) -> Path:
    path = Path(raw_path)
    if path.exists():
        return path
    if data_root is not None:
        parts = path.parts
        if "data" in parts:
            suffix = Path(*parts[parts.index("data") + 1 :])
            candidate = data_root / suffix
            if candidate.exists():
                return candidate
        candidate = data_root / path.name
        if candidate.exists():
            return candidate
    return path


def user_match_sql(user_key: str, allow_account_match: bool) -> str:
    clauses = [f"u.id_no = {sql_literal(user_key)}"]
    if allow_account_match:
        literal = sql_literal(user_key)
        clauses.extend([
            f"u.account_number = {literal}",
            f"u.user_number = {literal}",
            f"u.username = {literal}",
        ])
    return "(" + " OR ".join(clauses) + ")"


def export_sql(
    config_path: Path,
    output_path: Path,
    data_root: Path | None,
    default_model: str,
    allow_account_match: bool,
) -> None:
    config = json.loads(config_path.read_text(encoding="utf-8"))
    history_paths = config.get("history_chat_path")
    if not isinstance(history_paths, dict):
        raise SystemExit("config.json does not contain a valid history_chat_path object")

    statements: list[str] = [
        "-- Generated by scripts/export-legacy-chat-history-sql.py",
        "-- Import with: psql -U postgres -d lm_platform -f legacy_chat_import.sql",
        "BEGIN;",
    ]
    users_seen = 0
    users_missing_file = 0
    conversations_seen = 0
    messages_seen = 0

    for user_key, raw_path in sorted(history_paths.items()):
        if not isinstance(raw_path, str):
            continue
        history_path = resolve_history_path(raw_path, data_root)
        if not history_path.exists():
            users_missing_file += 1
            continue
        users_seen += 1
        conversations = load_conversations(history_path)
        for title, payload in conversations.items():
            messages = payload["messages"]
            if not messages:
                continue
            conversation_id = uuid.uuid5(NAMESPACE, f"conversation:{user_key}:{title}")
            created_at = parse_time(payload.get("time"))
            updated_at = created_at + timedelta(seconds=max(len(messages) - 1, 0))
            title_sql = sql_literal(clamp(title.replace('"', ""), 255))
            match_sql = user_match_sql(user_key, allow_account_match)
            statements.append(
                "INSERT INTO conversation ("
                "id, user_id, model_key, title, message_count, title_source, title_updated_at, created_at, updated_at"
                f") SELECT '{conversation_id}', u.id, {sql_literal(default_model)}, {title_sql}, {len(messages)}, "
                f"'manual', TIMESTAMPTZ {sql_literal(created_at.isoformat(sep=' '))}, "
                f"TIMESTAMPTZ {sql_literal(created_at.isoformat(sep=' '))}, "
                f"TIMESTAMPTZ {sql_literal(updated_at.isoformat(sep=' '))} "
                f"FROM app_user u WHERE {match_sql} "
                "ON CONFLICT (id) DO NOTHING;"
            )
            conversations_seen += 1
            for index, raw_message in enumerate(messages, start=1):
                if not isinstance(raw_message, dict):
                    continue
                role, content, reasoning = normalize_message(raw_message)
                message_id = uuid.uuid5(NAMESPACE, f"message:{user_key}:{title}:{index}")
                message_time = created_at + timedelta(seconds=index - 1)
                statements.append(
                    "INSERT INTO conversation_message ("
                    "id, conversation_id, sequence_no, role, content, status, reasoning_content, created_at, updated_at"
                    f") SELECT '{message_id}', c.id, {index}, {sql_literal(role)}, {sql_literal(content)}, "
                    f"'completed', {sql_literal(reasoning)}, "
                    f"TIMESTAMPTZ {sql_literal(message_time.isoformat(sep=' '))}, "
                    f"TIMESTAMPTZ {sql_literal(message_time.isoformat(sep=' '))} "
                    f"FROM conversation c WHERE c.id = '{conversation_id}' "
                    "ON CONFLICT (id) DO NOTHING;"
                )
                messages_seen += 1

    statements.extend([
        "COMMIT;",
        "",
    ])
    output_path.write_text("\n".join(statements), encoding="utf-8")
    print(
        "exported "
        f"users_with_files={users_seen}, missing_files={users_missing_file}, "
        f"conversations={conversations_seen}, messages={messages_seen}, "
        f"output={output_path}",
        file=sys.stderr,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate SQL for importing legacy chat history.")
    parser.add_argument("--config", required=True, type=Path, help="Legacy config.json path")
    parser.add_argument("--output", required=True, type=Path, help="SQL output path")
    parser.add_argument("--data-root", type=Path, help="Root that contains legacy per-user folders")
    parser.add_argument("--default-model", default="legacy-import", help="model_key used for imported conversations")
    parser.add_argument(
        "--allow-account-match",
        action="store_true",
        help="Also match legacy user key against account_number, user_number and username",
    )
    args = parser.parse_args()
    export_sql(args.config, args.output, args.data_root, args.default_model, args.allow_account_match)


if __name__ == "__main__":
    main()
